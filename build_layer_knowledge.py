"""Read every catalog row; compile semantic layer mappings and coverage evidence."""
import json
import sqlite3
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT/'rules/knowledge'
MAPPINGS = {'구조_벽체':'벽체','구조_창호':'창호','구조_출입문':'문','OCR':'문자'}
ALIASES = {'벽체':['벽체','벽','WALL'], '창호':['창호','WINDOW','WIN','GLAZ'],
           '문':['문','출입문','DOOR'], '기둥':['기둥','COLUMN','COL'],
           '가구':['가구','FURN','FURNITURE'], '위생기구':['위생기구','변기','세면대','욕조','SANITARY'],
           '주방기구':['주방기구','싱크대','가스레인지','KITCHENFIXTURE'],
           '치수':['치수','DIM','DIMS','DIMENSION'], '문자':['문자','TEXT','ANNO'],
           '해치':['해치','HATCH'], '중심선':['중심선','중심','AXIS','GRID','CENTER','CENTRE'],
           '조적':['조적','MASON','BRICK'], '계단':['계단','STAIR','STAIRS'],
           '승강기':['승강기','ELEVATOR'], '단열재':['단열재','INSULATION'],
           '경사로':['경사로','RAMP'], '대지':['대지','SITE'], '도로':['도로','ROAD']}


def build():
    db = sqlite3.connect(f'file:{(ROOT/"data/aihub-71465/full-catalog/catalog.sqlite").as_posix()}?mode=ro', uri=True)
    totals=Counter(); sheets=Counter(); splits=defaultdict(Counter); examples=defaultdict(list)
    rows=0; objects=0; issues=0
    for key, split, counts, count, issue in db.execute('SELECT id,split,class_counts,object_count,issue_count FROM drawings ORDER BY id'):
        rows+=1; objects+=count; issues+=bool(issue)
        for name,n in json.loads(counts).items():
            totals[name]+=n; sheets[name]+=1; splits[name][split]+=n
            if len(examples[name])<3: examples[name].append(key)
    db.close()
    rules=[]
    for name,n in sorted(totals.items()):
        target=MAPPINGS.get(name)
        if name.startswith('공간_'): target='공간_'+name.removeprefix('공간_')
        if name in ('객체_변기','객체_세면대','객체_욕조'): target='위생기구'
        if name in ('객체_싱크대','객체_가스레인지'): target='주방기구'
        rules.append({'id':'dataset.'+name,'className':name,'target':target,'objects':n,'sheets':sheets[name],
                      'splitObjects':dict(splits[name]),'sourceExamples':examples[name],
                      'basis':'verified_annotation_class','autoEligible':target is not None})
    data={'schemaVersion':1,'coverage':{'catalogRows':rows,'annotations':objects,'sheetsWithIssues':issues},
          'classRules':rules,'aliases':[{'id':'alias.'+k,'target':k,'tokens':v,'basis':'curated_convention','autoEligible':False} for k,v in ALIASES.items()],
          'policy':{'conflict':'keep_original','unknown':'keep_original','lockedHiddenReference':'exclude',
                    'spacePolygon':'space_layer_not_wall_or_fixture','colorAlone':'never_classify',
                    'geometricHeuristics':'review_only','confidenceIsProbability':False},
          'limitations':['Catalog labels contain semantic classes, not original DWG layer names.',
                         'All catalog rows were aggregated, not visually re-recognized.',
                         'Validation split counts are coverage, not independent accuracy measurement.']}
    OUT.mkdir(parents=True,exist_ok=True)
    prior_counts=Counter()
    for r in rules:
        if r['target']: prior_counts[r['target']]+=r['splitObjects'].get('Training',0)
    labels=sorted(set(prior_counts)|set(ALIASES))
    denominator=sum(prior_counts.values())+len(labels)
    ranking={'schemaVersion':1,'model':'tempered_prior_weighted_softmax','calibrated':False,
        'priorSource':'Training annotation counts only; Laplace smoothing alpha=1',
        'priors':{label:(prior_counts[label]+1)/denominator for label in labels},
        'priorStrength':0.1,'weights':{'native':8,'annotation':8,'name':4,'geometry':4.5},
        'unknownLogit':2,'minimumScore':0.55,'minimumMargin':0.25,
        'conflictingStrongEvidence':'review','geometryRequiresVerifiedMm':True,'maxGeometryEntities':2000,
        'missingEvidence':'unknown','feedbackPolicy':'never_train_on_automatic_predictions',
        'scoreMeaning':'Normalized model hypothesis score, not measured accuracy probability'}
    (OUT/'layer-ranking.json').write_text(json.dumps(ranking,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'layer-ranking-data.js').write_text('// Generated by build_layer_knowledge.py\nexport const LAYER_RANKING = '+json.dumps(ranking,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
    rank_schema={'$schema':'http://json-schema.org/draft-07/schema#','type':'object','additionalProperties':False,
        'required':list(ranking), 'properties':{
            'schemaVersion':{'const':1},'model':{'const':'tempered_prior_weighted_softmax'},'calibrated':{'const':False},
            'priorSource':{'type':'string'},'priors':{'type':'object','minProperties':1,'additionalProperties':{'type':'number','exclusiveMinimum':0,'maximum':1}},
            'priorStrength':{'type':'number','minimum':0,'maximum':1},
            'weights':{'type':'object','additionalProperties':False,'required':['native','annotation','name','geometry'],'properties':{key:{'type':'number','minimum':0,'maximum':20} for key in ranking['weights']}},
            'unknownLogit':{'type':'number','minimum':0,'maximum':20},
            'minimumScore':{'type':'number','minimum':0.5,'maximum':1},'minimumMargin':{'type':'number','minimum':0,'maximum':1},
            'conflictingStrongEvidence':{'const':'review'},'geometryRequiresVerifiedMm':{'const':True},'maxGeometryEntities':{'type':'integer','minimum':0,'maximum':2000},
            'missingEvidence':{'const':'unknown'},'feedbackPolicy':{'const':'never_train_on_automatic_predictions'},'scoreMeaning':{'type':'string'}}}
    (OUT/'layer-ranking.schema.json').write_text(json.dumps(rank_schema,ensure_ascii=False,indent=2),encoding='utf-8')
    decision_schema={'$schema':'http://json-schema.org/draft-07/schema#','type':'object',
        'required':['id','label','accepted','modelScore','margin','candidates','calibrated','ruleIds','status','reason'],
        'properties':{'id':{'type':'string'},'label':{'type':['string','null']},'accepted':{'type':'boolean'},
            'modelScore':{'type':'number','minimum':0,'maximum':1},'margin':{'type':'number','minimum':0,'maximum':1},
            'calibrated':{'const':False},'ruleIds':{'type':'array','items':{'type':'string'}},'status':{'enum':['auto','review']},'reason':{'type':'string'},
            'candidates':{'type':'array','minItems':2,'items':{'type':'object','additionalProperties':False,'required':['label','score','ruleIds'],
                'properties':{'label':{'type':['string','null']},'score':{'type':'number','minimum':0,'maximum':1},'ruleIds':{'type':'array','items':{'type':'string'}}}}}}}
    (OUT/'layer-decision.schema.json').write_text(json.dumps(decision_schema,ensure_ascii=False,indent=2),encoding='utf-8')
    (OUT/'layer-knowledge.json').write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'layer-knowledge-data.js').write_text('// Generated by build_layer_knowledge.py; do not edit.\nexport const LAYER_KNOWLEDGE = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
    schema={'$schema':'http://json-schema.org/draft-07/schema#','type':'object','required':['schemaVersion','coverage','classRules','aliases','policy','limitations'],
            'properties':{'schemaVersion':{'const':1},'coverage':{'type':'object','required':['catalogRows','annotations','sheetsWithIssues'],'additionalProperties':{'type':'integer','minimum':0}},
             'classRules':{'type':'array','items':{'type':'object','required':['id','className','target','objects','sheets','splitObjects','sourceExamples','basis','autoEligible'],
                'properties':{'id':{'type':'string'},'className':{'type':'string'},'target':{'type':['string','null']},'objects':{'type':'integer','minimum':0},'sheets':{'type':'integer','minimum':0},'splitObjects':{'type':'object','additionalProperties':{'type':'integer','minimum':0}},'sourceExamples':{'type':'array','items':{'type':'string'}},'basis':{'const':'verified_annotation_class'},'autoEligible':{'type':'boolean'}}}},
             'aliases':{'type':'array','items':{'type':'object','required':['id','target','tokens','basis','autoEligible'],'properties':{'id':{'type':'string'},'target':{'type':'string'},'tokens':{'type':'array','items':{'type':'string'}},'basis':{'const':'curated_convention'},'autoEligible':{'const':False}}}},'policy':{'type':'object'},'limitations':{'type':'array','items':{'type':'string'}}}}
    (OUT/'layer-knowledge.schema.json').write_text(json.dumps(schema,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'coverage':data['coverage'],'classRules':len(rules),'mappedAnnotations':sum(r['objects'] for r in rules if r['target']),'unmappedClasses':[r['className'] for r in rules if not r['target']]},ensure_ascii=False))

if __name__=='__main__': build()
