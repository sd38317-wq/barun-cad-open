export function menuCoverage(commands){
 const known=new Set(commands.map(c=>c.name)),placements=new Map(),unknown=[];
 for(const [tab,menu] of Object.entries(MENU_CATALOG))for(const group of menu.sections)for(const name of group.commands){
  if(!known.has(name))unknown.push(name);
  const entries=placements.get(name)||[];entries.push({tab,group:group.label});placements.set(name,entries);
 }
 const internalAliases=new Set(Object.keys(MENU_COMPAT_ALIASES));
 return {missing:[...known].filter(name=>!placements.has(name)&&!internalAliases.has(name)&&!MENU_HIDDEN_COMMANDS.has(name)),unknown,duplicates:[...placements].filter(([,entries])=>entries.length>1).map(([name])=>name)};
}

export function matchesMenuQuery(text,query){
 const haystack=String(text).toLocaleLowerCase('ko');
 return String(query).trim().toLocaleLowerCase('ko').split(/\s+/).every(word=>haystack.includes(word));
}
