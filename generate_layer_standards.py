"""Generate UI specs and standalone Lisp tables from one source; no application build."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'rules/knowledge/generation-layer-standards.json'

def records():
    return json.loads(SOURCE.read_text(encoding='utf-8'))['layers']

def rendered():
    return '// Generated by generate_layer_standards.py; edit rules/knowledge/generation-layer-standards.json.\nexport const LAYER_STANDARDS = ' + json.dumps(records(), ensure_ascii=False, indent=2) + ';\n'

def lisp_table():
    rows = [layer for layer in records() if 'template' in layer['groups']]
    linetypes = ' '.join('"' + name + '"' for name in sorted({layer['linetype'] for layer in rows} - {'CONTINUOUS'}))
    values = '\n    '.join('("{}" {} "{}" {} {})'.format(layer['name'], int(layer['color'][1:], 16), layer['linetype'], round(layer['lineweight'] * 100), int(layer['plot'])) for layer in rows)
    return '''(defun ARCH:표준레이어 ()
  ;; Generated by generate_layer_standards.py from generation-layer-standards.json.
  (foreach lt '(LINETYPES)
    (if (not (tblsearch "LTYPE" lt))
      (command "_.-linetype" "_load" lt "acad.lin" "")))
  (foreach x '(VALUES)
    (if (not (tblsearch "LAYER" (car x)))
      (entmake (list '(0 . "LAYER") '(100 . "AcDbSymbolTableRecord")
        '(100 . "AcDbLayerTableRecord") (cons 2 (car x)) '(62 . 7)
        (cons 420 (cadr x)) (cons 6 (caddr x)) (cons 370 (nth 3 x))
        (cons 290 (nth 4 x)) '(70 . 0))))))
'''.replace('VALUES', values).replace('LINETYPES', linetypes)

def generate():
    (ROOT / 'layer-standards-data.js').write_text(rendered(), encoding='utf-8', newline='\n')
    for target in sorted((ROOT / 'examples/architecture-lisp').glob('*.lsp')):
        original = target.read_bytes().decode('utf-8')
        newline = '\r\n' if '\r\n' in original else '\n'
        text = original.replace('\r\n', '\n')
        text, count = re.subn(r'\(defun ARCH:표준레이어 \(\)[\s\S]*?(?=\(defun ARCH:실수)', lambda match: lisp_table(), text, count=1)
        if count != 1:
            raise ValueError(f'Missing Lisp table: {target.name}')
        target.write_bytes(text.replace('\n', newline).encode('utf-8'))

if __name__ == '__main__':
    generate()
